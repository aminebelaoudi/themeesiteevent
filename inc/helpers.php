/**
 * Return a Carbon Fields value with optional escaping.
 */
function easyevents_cf( $field_name, $context = 'post', $escape = 'html' ) {
	if ( ! function_exists( 'carbon_get_theme_option' ) ) {
		return '';
	}

	$value = ( 'theme' === $context )
		? carbon_get_theme_option( $field_name )
		: carbon_get_the_post_meta( $field_name );

	if ( 'url' === $escape ) {
		return esc_url( $value );
	}
	if ( 'raw' === $escape ) {
		return $value;
	}
	return esc_html( $value );
}
